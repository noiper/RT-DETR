#!/usr/bin/env python3
from __future__ import annotations

import argparse
import contextlib
import io
import json
import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np
import torch
from PIL import Image
from pycocotools.coco import COCO
from pycocotools.cocoeval import COCOeval
from tqdm import tqdm

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from src.core import YAMLConfig
from src.data._misc import convert_to_tv_tensor
from src.zoo.temporal_rtdetr import TemporalRTDETR


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Evaluate Temporal RT-DETR on key->terminal MOT17 subset pairs."
    )
    parser.add_argument("--config", "-c", type=str, required=True, help="Path to model config YAML.")
    parser.add_argument("--weights", "-w", type=str, required=True, help="Path to checkpoint .pth file.")
    parser.add_argument(
        "--pairs-json",
        type=Path,
        required=True,
        help="Path to *_pairs.json generated by subset scripts.",
    )
    parser.add_argument(
        "--mode",
        type=str,
        choices=["nonkey", "baseline", "key"],
        default="nonkey",
        help=(
            "Inference mode: "
            "nonkey=key frame cached then non-key forward on terminal frame; "
            "baseline=key detections reused on terminal frame; "
            "key=full key-path inference directly on terminal frame."
        ),
    )
    parser.add_argument(
        "--nonkey-score",
        type=float,
        default=1.0,
        help="Scale detection scores in nonkey/baseline mode before evaluation.",
    )
    parser.add_argument(
        "--max-pairs",
        type=int,
        default=None,
        help="Optional limit for quick debugging.",
    )
    parser.add_argument(
        "--device",
        type=str,
        default=None,
        help="Explicit device (for example: cuda, cuda:0, cpu). Default: auto.",
    )
    parser.add_argument(
        "--save-detections",
        type=Path,
        default=None,
        help="Optional path to save COCO detections JSON.",
    )
    return parser.parse_args()


def load_pairs(path: Path) -> Tuple[Dict[str, Any], List[Dict[str, Any]]]:
    with path.open("r", encoding="utf-8") as f:
        payload = json.load(f)
    pairs = payload.get("pairs", [])
    if not pairs:
        raise ValueError(f"No pairs found in {path}")
    return payload, pairs


def _get_model_dims(cfg: YAMLConfig) -> Tuple[int, int]:
    hidden_dim = 256
    num_queries = 300
    if "RTDETRTransformerv2" in cfg.yaml_cfg:
        decoder_cfg = cfg.yaml_cfg["RTDETRTransformerv2"]
        hidden_dim = decoder_cfg.get("hidden_dim", 256)
        num_queries = decoder_cfg.get("num_queries", 300)
    elif "RTDETRTransformer" in cfg.yaml_cfg:
        decoder_cfg = cfg.yaml_cfg["RTDETRTransformer"]
        hidden_dim = decoder_cfg.get("hidden_dim", 256)
        num_queries = decoder_cfg.get("num_queries", 300)
    return int(hidden_dim), int(num_queries)


def build_temporal_model(cfg: YAMLConfig, weights_path: str, device: torch.device) -> Tuple[TemporalRTDETR, Any]:
    base_model = cfg.model.to(device)
    hidden_dim, num_queries = _get_model_dims(cfg)
    model = TemporalRTDETR(
        backbone=base_model.backbone,
        encoder=getattr(base_model, "encoder", None),
        decoder=getattr(base_model, "decoder", None),
        num_classes=cfg.yaml_cfg.get("num_classes", 80),
        hidden_dim=hidden_dim,
        num_queries=num_queries,
        use_lightweight_decoder=cfg.yaml_cfg.get("use_lightweight_decoder", False),
        reuse_position=cfg.yaml_cfg.get("reuse_position", 0),
    ).to(device)

    checkpoint = torch.load(weights_path, map_location=device, weights_only=False)
    state_dict = checkpoint.get("model_state_dict", checkpoint.get("model", checkpoint))
    is_decoupled = any("lightweight_decoder.dec_score_head" in k for k in state_dict.keys())
    if is_decoupled:
        model.decouple_non_key_prediction_heads()
    model.load_state_dict(state_dict, strict=True)
    model.eval()
    return model, cfg.postprocessor


def _prepare_target_for_transforms(img_info: Dict[str, Any], anns: List[Dict[str, Any]]) -> Dict[str, Any]:
    boxes = []
    labels = []
    areas = []
    iscrowd = []
    for ann in anns:
        x, y, w, h = ann["bbox"]
        boxes.append([x, y, x + w, y + h])
        labels.append(int(ann["category_id"]))
        areas.append(float(ann.get("area", w * h)))
        iscrowd.append(int(ann.get("iscrowd", 0)))

    h = int(img_info["height"])
    w = int(img_info["width"])
    target = {
        "boxes": torch.as_tensor(boxes, dtype=torch.float32) if boxes else torch.zeros((0, 4), dtype=torch.float32),
        "labels": torch.as_tensor(labels, dtype=torch.int64) if labels else torch.zeros((0,), dtype=torch.int64),
        "image_id": torch.tensor([int(img_info["id"])]),
        "area": torch.as_tensor(areas, dtype=torch.float32) if areas else torch.zeros((0,), dtype=torch.float32),
        "iscrowd": torch.as_tensor(iscrowd, dtype=torch.int64) if iscrowd else torch.zeros((0,), dtype=torch.int64),
        "orig_size": torch.as_tensor([w, h], dtype=torch.int64),
        "size": torch.as_tensor([w, h], dtype=torch.int64),
    }
    target["boxes"] = convert_to_tv_tensor(target["boxes"], key="boxes", spatial_size=(h, w))
    return target


def _apply_transforms(
    transforms: Any,
    image: Image.Image,
    target: Dict[str, Any],
) -> Tuple[torch.Tensor, Dict[str, Any]]:
    if transforms is None:
        import torchvision.transforms.functional as F

        image = F.resize(image, [640, 640])
        image = F.to_tensor(image)
        target["size"] = torch.as_tensor([640, 640], dtype=torch.int64)
        return image, target

    try:
        out = transforms(image, target)
    except TypeError:
        out = transforms(image, target, None)
    if isinstance(out, (list, tuple)):
        image_out, target_out = out[:2]
    else:
        raise RuntimeError("Unexpected transforms output type.")
    return image_out, target_out


def load_tensor_and_target(
    root_dir: Path,
    img_info: Dict[str, Any],
    anns: List[Dict[str, Any]],
    transforms: Any,
) -> Tuple[torch.Tensor, Dict[str, Any]]:
    image_path = root_dir / img_info["file_name"]
    image = Image.open(image_path).convert("RGB")
    target = _prepare_target_for_transforms(img_info, anns)
    return _apply_transforms(transforms, image, target)


def format_coco_single(target: Dict[str, Any], output: Dict[str, torch.Tensor], score_scale: float) -> List[Dict[str, Any]]:
    image_id = int(target["image_id"].item())
    boxes = output["boxes"].detach().cpu().numpy()
    scores = (output["scores"].detach().cpu().numpy() * score_scale).tolist()
    labels = output["labels"].detach().cpu().numpy().tolist()
    detections = []
    for i in range(len(scores)):
        x1, y1, x2, y2 = boxes[i]
        detections.append(
            {
                "image_id": image_id,
                "category_id": int(labels[i]),
                "bbox": [float(x1), float(y1), float(x2 - x1), float(y2 - y1)],
                "score": float(scores[i]),
            }
        )
    return detections


def evaluate_map(coco_gt: COCO, detections: List[Dict[str, Any]], terminal_ids: List[int]) -> np.ndarray:
    coco_gt.dataset.setdefault("info", {})
    coco_gt.dataset.setdefault("licenses", [])

    if detections:
        coco_dt = coco_gt.loadRes(detections)
    else:
        coco_dt = coco_gt.loadRes([])

    evaluator = COCOeval(coco_gt, coco_dt, "bbox")
    evaluator.params.imgIds = sorted(set(int(x) for x in terminal_ids))
    evaluator.evaluate()
    evaluator.accumulate()
    with contextlib.redirect_stdout(io.StringIO()):
        evaluator.summarize()
    if len(evaluator.stats) < 12:
        return np.zeros(12, dtype=np.float32)
    return evaluator.stats


def main() -> None:
    args = parse_args()
    payload, pairs = load_pairs(args.pairs_json.resolve())
    if args.max_pairs is not None:
        pairs = pairs[: max(0, args.max_pairs)]
    if not pairs:
        raise ValueError("No pairs left after applying --max-pairs.")

    device = torch.device(args.device) if args.device else torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"device: {device}")
    print(f"mode:   {args.mode}")
    print(f"pairs:  {len(pairs)}")

    ann_path = Path(payload["ann_file"]).resolve()
    coco = COCO(str(ann_path))
    coco.dataset.setdefault("info", {})
    coco.dataset.setdefault("licenses", [])
    images_by_id = coco.imgs
    anns_by_image_id = coco.imgToAnns

    cfg = YAMLConfig(args.config)
    model, postprocessor = build_temporal_model(cfg, args.weights, device)

    dataset_cfg = cfg.yaml_cfg.get("val_dataloader", {}).get("dataset", {})
    root_dir = Path(dataset_cfg.get("root_dir", "")).resolve()
    if not root_dir.exists():
        raise FileNotFoundError(f"Dataset root_dir from config does not exist: {root_dir}")

    transforms = cfg.val_dataloader.dataset.transforms

    detections: List[Dict[str, Any]] = []
    terminal_ids: List[int] = []

    with torch.no_grad():
        for pair in tqdm(pairs, desc="subset inference"):
            key_image_id = int(pair["key_image_id"])
            terminal_image_id = int(pair["terminal_image_id"])
            key_info = images_by_id[key_image_id]
            terminal_info = images_by_id[terminal_image_id]

            key_img, key_target = load_tensor_and_target(
                root_dir=root_dir,
                img_info=key_info,
                anns=anns_by_image_id.get(key_image_id, []),
                transforms=transforms,
            )
            terminal_img, terminal_target = load_tensor_and_target(
                root_dir=root_dir,
                img_info=terminal_info,
                anns=anns_by_image_id.get(terminal_image_id, []),
                transforms=transforms,
            )

            key_img = key_img.unsqueeze(0).to(device)
            terminal_img = terminal_img.unsqueeze(0).to(device)

            terminal_orig = terminal_target["orig_size"].unsqueeze(0).to(device)

            if args.mode == "key":
                out = model.forward_key_frame(terminal_img, None)
                pred = postprocessor(out, terminal_orig)[0]
                score_scale = 1.0
            else:
                out_key = model.forward_key_frame(key_img, None)
                if args.mode == "baseline":
                    norm_size = torch.tensor([[1.0, 1.0]], device=device)
                    key_norm = postprocessor(out_key, norm_size)[0]
                    pred = {
                        "boxes": key_norm["boxes"] * terminal_orig.repeat(1, 2).squeeze(0),
                        "scores": key_norm["scores"],
                        "labels": key_norm["labels"],
                    }
                else:
                    out_nk = model.forward_non_key_frame(terminal_img, None)
                    pred = postprocessor(out_nk, terminal_orig)[0]
                score_scale = float(args.nonkey_score)

            detections.extend(format_coco_single(terminal_target, pred, score_scale=score_scale))
            terminal_ids.append(terminal_image_id)

    stats = evaluate_map(coco_gt=coco, detections=detections, terminal_ids=terminal_ids)
    print("\n=== Terminal Subset Results ===")
    print(f"mAP:   {stats[0]:.4f}")
    print(f"mAP50: {stats[1]:.4f}")
    print(f"mAP75: {stats[2]:.4f}")
    print(f"mAP_s: {stats[3]:.4f}")
    print(f"mAP_m: {stats[4]:.4f}")
    print(f"mAP_l: {stats[5]:.4f}")
    print(f"terminal frames evaluated: {len(set(terminal_ids))}")

    if args.save_detections is not None:
        args.save_detections.parent.mkdir(parents=True, exist_ok=True)
        with args.save_detections.open("w", encoding="utf-8") as f:
            json.dump(detections, f)
            f.write("\n")
        print(f"detections saved: {args.save_detections.resolve()}")


if __name__ == "__main__":
    main()
